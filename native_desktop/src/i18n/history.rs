#[cfg(test)]
mod tests {
    use super::*;
    use crate::i18n::LOCALES;

    #[test]
    fn history_messages_are_unique_and_complete_across_all_locales() {
        for (index, key) in KEYS.iter().enumerate() {
            assert!(!KEYS[..index].contains(key), "duplicate source: {key}");
            assert_eq!(translated("en", key), Some(*key));
            for locale in LOCALES {
                let value = translated(locale, key).expect("known history source");
                assert!(!value.trim().is_empty(), "{locale}: {key}");
                assert!(!value.contains('{'), "{locale}: {key}");
            }
        }
        assert_eq!(translated("pt-BR", "Refresh"), Some("Refresh"));
        assert_eq!(translated("unknown", "Refresh"), Some("Refresh"));
        assert_eq!(translated("ru", "Untrusted peer text"), None);
    }

    #[test]
    fn history_status_and_privacy_messages_remain_distinct() {
        for locale in LOCALES {
            let get = |key| translated(locale, key).expect("history key");
            let success = get("Completed");
            for failure in [
                "Declined",
                "Cancelled",
                "Failed",
                "Disconnected",
                "Interrupted",
                "In progress",
            ] {
                assert_ne!(
                    success,
                    get(failure),
                    "{locale}: {failure} confused with success"
                );
            }
            assert_ne!(
                get("Declined"),
                get("Cancelled"),
                "{locale}: decline/cancel collision"
            );
            assert_ne!(
                get("Clear completed"),
                get("Reset history"),
                "{locale}: destructive action collision"
            );
            assert_ne!(
                get("Service disconnected. Live states may be stale; reconnect before controlling a transfer."),
                get("History could not be read safely. Refresh to retry; sharing remains available."),
                "{locale}: disconnected/read error collision"
            );
            let retention = get("Completed metadata is kept for up to 30 days and 1000 operations. File and message contents are not stored.");
            assert!(
                retention.contains("30") && retention.contains("1000"),
                "{locale}: retention constants"
            );
            assert_ne!(
                retention,
                get("Completed"),
                "{locale}: privacy warning collision"
            );
        }
        assert_eq!(translated("ru", "Reset history"), Some("Сбросить историю"));
        assert_eq!(translated("pt", "Reset history"), Some("Repor histórico"));
        assert_eq!(translated("ru", "Declined"), Some("Отклонено"));
        assert_eq!(translated("pt", "Cancelled"), Some("Cancelado"));
        assert_eq!(translated("zh-Hant", "Completed"), Some("已完成"));
    }
}
