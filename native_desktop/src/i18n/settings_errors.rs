#[cfg(test)]
mod tests {
    use super::*;
    use crate::i18n::LOCALES;

    #[test]
    fn action_error_catalog_is_complete_in_all_20_locales() {
        for (index, source) in KEYS.iter().enumerate() {
            assert!(!KEYS[..index].contains(source), "duplicate action error");
            assert_eq!(translated("en", source), Some(*source));
            for locale in LOCALES {
                let caption = translated(locale, source).expect("known error");
                assert!(!caption.trim().is_empty(), "{locale}: {source}");
                assert!(!caption.contains('{'), "{locale}: {source}");
            }
        }
        assert_eq!(
            translated("pt-BR", "Save outcome is uncertain. Retry the same save."),
            Some("Save outcome is uncertain. Retry the same save.")
        );
        assert_eq!(translated("unknown", "Bad peer data"), None);
    }

    #[test]
    fn uncertain_rejected_lost_and_recovery_actions_cannot_collide() {
        for locale in LOCALES {
            let get = |source| translated(locale, source).expect("known action error");
            for (left, right) in [
                (KEYS[0], KEYS[1]),
                (KEYS[1], KEYS[4]),
                (KEYS[1], KEYS[5]),
                (KEYS[1], KEYS[9]),
                (KEYS[2], KEYS[3]),
                (KEYS[3], KEYS[4]),
                (KEYS[6], KEYS[7]),
                (KEYS[7], KEYS[8]),
                (KEYS[11], KEYS[12]),
                (KEYS[12], KEYS[13]),
                (KEYS[13], KEYS[15]),
                (KEYS[14], KEYS[16]),
            ] {
                assert_ne!(get(left), get(right), "{locale}: {left} vs {right}");
            }
        }
        assert_eq!(
            translated("ru", "Save outcome is uncertain. Retry the same save."),
            Some("Результат сохранения неизвестен. Повторите то же сохранение.")
        );
        assert_eq!(
            translated("pt", "Login change is unconfirmed. Reload the actual state; no write will be repeated."),
            Some("A alteração do arranque não foi confirmada. Recarregue o estado real; a gravação não será repetida.")
        );
    }
}
