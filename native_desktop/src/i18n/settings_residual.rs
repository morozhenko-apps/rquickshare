#[cfg(test)]
mod tests {
    use super::*;
    use crate::i18n::LOCALES;

    #[test]
    fn given_supported_locales_when_rendering_residual_settings_then_every_key_is_present() {
        for (index, key) in KEYS.iter().enumerate() {
            assert!(
                !KEYS[..index].contains(key),
                "duplicate residual source key"
            );
            assert_eq!(translated("en", key), Some(*key));
            for locale in LOCALES {
                let text = translated(locale, key).expect("known settings string");
                assert!(!text.trim().is_empty(), "{locale}: {key}");
                assert!(!text.contains('{'), "{locale}: {key}");
            }
        }
        assert_eq!(translated("pt-BR", KEYS[5]), Some("Start sharing"));
        assert_eq!(translated("zh-Hans", KEYS[5]), Some("Start sharing"));
        assert_eq!(translated("unknown", "Untrusted peer"), None);
    }

    #[test]
    fn given_sensitive_messages_when_translating_then_pending_and_off_remain_distinct() {
        for locale in LOCALES {
            let get = |source| translated(locale, source).expect("known settings key");
            for (first, second) in [
                (KEYS[4], KEYS[8]),
                (KEYS[5], KEYS[12]),
                (KEYS[6], KEYS[7]),
                (KEYS[6], KEYS[10]),
                (KEYS[7], KEYS[8]),
                (KEYS[8], KEYS[9]),
                (KEYS[9], KEYS[10]),
                (KEYS[11], KEYS[12]),
                (KEYS[13], KEYS[14]),
            ] {
                assert_ne!(get(first), get(second), "{locale}: {first}/{second}");
            }
            assert!(get(KEYS[3]).contains("GNU General Public License v3.0."));
        }
        assert_eq!(translated("ru", KEYS[5]), Some("Запустить обмен"));
        assert_eq!(translated("pt", KEYS[5]), Some("Iniciar partilha"));
    }
}
